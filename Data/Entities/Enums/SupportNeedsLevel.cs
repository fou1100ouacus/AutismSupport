namespace Data.Entities.Enums
{
    /// <summary>
    /// Defines the level of support needs for individuals in the autism support system
    /// </summary>
    public enum SupportNeedsLevel
    {
        /// <summary>
        /// Light support needs - requires minimal assistance and can function independently with occasional guidance
        /// </summary>
        Light = 1,
        /// <summary>
        /// Medium support needs - requires regular assistance and support for daily activities
        /// </summary>
        Medium = 2,
        /// <summary>
        /// High support needs - requires substantial assistance and continuous support for daily activities
        /// </summary>
        High = 3
    }
}